// Данные для глобуса: world-atlas (Natural Earth 110m). Страны идентифицируются числовым кодом ISO 3166-1
// (строка из 3 цифр, например '076' — Бразилия). Рисует глобус canvas (см. WorldMap.jsx).
import { feature } from 'topojson-client'
import { geoBounds, geoCentroid } from 'd3-geo'
import { INFO } from './capitals'
import topo from 'world-atlas/countries-110m.json'

export const COUNTRIES = feature(topo, topo.objects.countries).features
  .map((f) => {
    const id = String(f.id ?? f.properties.name).padStart(3, '0')
    const [[w, s], [e, n]] = geoBounds(f)
    const size = Math.max(e < w ? e + 360 - w : e - w, n - s) // угловой размер страны, °
    return { id, name: f.properties.name, f, c: geoCentroid(f), size }
  })
  .filter((c) => c.id !== '010' && c.size > 0) // без Антарктиды

