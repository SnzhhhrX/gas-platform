const polysOf = (f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates])
function shapeOf(pts) {
  const out = []
  for (const pt of pts) {
    const c = COUNTRIES.find((x) => geoContains(x.f, pt))
    const poly = c && polysOf(c.f).find((p) => geoContains({ type: 'Polygon', coordinates: p }, pt))
    if (poly && !out.includes(poly)) out.push(poly)
  }
  return out.length ? { type: 'Feature', geometry: { type: 'MultiPolygon', coordinates: out } } : null
}

// Формат как у COUNTRIES (id, f, c, size) — WorldMap рисует и проверяет их так же
export const ISLANDS = RAW.map(([id, name, level, pts, fact]) => {
  const f = shapeOf(pts)
  if (!f) return null
  const [[w, s], [e, n]] = geoBounds(f)
  return { id: `i-${id}`, name, level, fact, f, c: geoCentroid(f), size: Math.max(e < w ? e + 360 - w : e - w, n - s) }
}).filter(Boolean)

export const islandName = (id) => ISLANDS.find((x) => x.id === id)?.name ?? id
