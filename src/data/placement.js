// Количество вопросов на навык
export const PER_SKILL = 3
// Первый, второй и третий вопрос по навыку: [уровень, номер в списке уровня], если уже даны ответы res = [{ ok }, ...]. null — навык закончен.
const keyFor = (res) => {
  if (res.length === 0) return ['d2', 0]
  if (res.length === 1) return res[0].ok ? ['d3', 0] : ['d1', 0]
  if (res.length === 2) return res[0].ok && res[1].ok ? ['d3', 1] : !res[0].ok && !res[1].ok ? ['d1', 1] : ['d2', 1]
  return null
}
const resultsOf = (answers, skill) => answers.filter((a) => a.skill === skill)

// Следующий вопрос теста: идём «кругами» по навыкам (в порядке order), чтобы тест можно было остановить в любой момент.
// seed (номер попытки) сдвигает выбор вопроса внутри уровня, чтобы при пересдаче были другие вопросы.
export function nextStep(answers, order, seed = 0) {
  for (let round = 0; round < PER_SKILL; round++) {
    for (const skill of order) {
      const res = resultsOf(answers, skill)
      if (res.length !== round) continue
      const key = keyFor(res)
      if (!key) continue
      const [d, slot] = key
      const list = BANK[skill][d]
      const base = list[(slot + seed) % list.length]
      return { skill, key: `${d}:${slot}`, level: d, q: varyQuestion(base) }
    }
  }
  return null
}
// Сколько вопросов осталось максимум (для полоски прогресса)
export const expectedTotal = (order) => order.length * PER_SKILL
