const TOUR_POOL = [...olympiadLessons, ...MORE_LESSONS.filter((l) => l.id.startsWith('pro-'))]
  .flatMap((l) => l.questions).filter((q) => !['map', 'mapid'].includes(q.type))
const tour = (n) => { const step = TOUR_POOL.length / n; return Array.from({ length: n }, (_, i) => varyQuestion(TOUR_POOL[Math.floor(i * step)])) }
